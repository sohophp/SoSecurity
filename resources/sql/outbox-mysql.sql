-- Explicit deployment only. Same transaction database/connection as the business tables.

CREATE TABLE sosecurity_outbox_roots (
    namespace CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    format BIGINT UNSIGNED NOT NULL,
    epoch CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    policy CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    entries BIGINT UNSIGNED NOT NULL,
    history_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    last_order BIGINT UNSIGNED NOT NULL,
    revision BIGINT UNSIGNED NOT NULL,
    created_at BIGINT UNSIGNED NOT NULL,
    observed_at BIGINT UNSIGNED NOT NULL,
    seal_key VARBINARY(32) NOT NULL,
    seal CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRIMARY KEY (namespace)
) ENGINE=InnoDB;

CREATE TABLE sosecurity_outbox_records (
    namespace CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    message_id VARBINARY(96) NOT NULL,
    format BIGINT UNSIGNED NOT NULL,
    epoch CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    policy CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    delivery_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    order_no BIGINT UNSIGNED NOT NULL,
    fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    destination VARBINARY(64) NOT NULL,
    topic VARBINARY(64) NOT NULL,
    aggregate_id VARBINARY(256) NOT NULL,
    aggregate_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_bytes BIGINT UNSIGNED NOT NULL,
    payload_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_present BIGINT UNSIGNED NOT NULL,
    payload_body MEDIUMBLOB NOT NULL,
    status VARBINARY(16) NOT NULL,
    attempts BIGINT UNSIGNED NOT NULL,
    cycle_attempts BIGINT UNSIGNED NOT NULL,
    manual_retries BIGINT UNSIGNED NOT NULL,
    created_at BIGINT UNSIGNED NOT NULL,
    admit_until BIGINT UNSIGNED NOT NULL,
    deliver_until BIGINT UNSIGNED NOT NULL,
    available_at BIGINT UNSIGNED NOT NULL,
    lease_until BIGINT UNSIGNED NOT NULL,
    generation BIGINT UNSIGNED NOT NULL,
    worker_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    token_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    last_error VARBINARY(64) NOT NULL,
    updated_at BIGINT UNSIGNED NOT NULL,
    sent_at BIGINT UNSIGNED NOT NULL,
    seal_key VARBINARY(32) NOT NULL,
    seal CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRIMARY KEY (namespace,key_hash),
    UNIQUE KEY sosecurity_outbox_order (namespace,order_no),
    KEY sosecurity_outbox_aggregate (namespace,aggregate_hash,order_no),
    KEY sosecurity_outbox_due (namespace,status,available_at,order_no)
) ENGINE=InnoDB;
