<?php
declare(strict_types=1);
require __DIR__ . '/bootstrap.php';
use SoSecurity\Storage\MySqlStore;
use SoSecurity\Storage\Change;
use SoSecurity\Storage\StorageException;
use SoSecurity\Exception\ConfigurationException;

$socket = getenv('SOSECURITY_TEST_MYSQL_SOCKET');
if (!$socket) { echo "NOT RUN MySQL integration: isolated socket required\n"; exit(0); }
$pdo = new PDO('mysql:unix_socket=' . $socket . ';dbname=sosecurity_test;charset=utf8mb4', 'sosecurity_test', 'integration-only', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pdo->exec('DROP TABLE IF EXISTS sosecurity_state');
Check::throws(ConfigurationException::class, function () use ($pdo) { new MySqlStore($pdo, 'test'); });
MySqlStore::install($pdo);
$clock = new TestClock(); $store = new MySqlStore($pdo, 'test', $clock); $other = new MySqlStore($pdo, 'other', $clock);
$mode = $pdo->getAttribute(PDO::ATTR_ERRMODE);
$timeout = $pdo->query('SELECT @@SESSION.innodb_lock_wait_timeout')->fetchColumn();
Check::same(null, $store->transact('key', function ($value) { return new Change(['n' => 1], 100001, $value); }));
Check::same(['n' => 1], $store->transact('key', function ($value) { return new Change($value, 100001, $value); }));
Check::same(null, $other->transact('key', function ($value) { return new Change(null, 0, $value); }));
Check::throws(RuntimeException::class, function () use ($store) { $store->transact('key', function () { throw new RuntimeException('callback failed'); }); });
Check::same(['n' => 1], $store->transact('key', function ($value) { return new Change($value, 100001, $value); }));
Check::same(false, $pdo->inTransaction());
Check::same($mode, $pdo->getAttribute(PDO::ATTR_ERRMODE));
Check::same((string) $timeout, (string) $pdo->query('SELECT @@SESSION.innodb_lock_wait_timeout')->fetchColumn());
$clock->time++;
Check::same(null, $store->transact('key', function ($value) { return new Change(['n' => 2], 0, $value); }));
$pdo->beginTransaction();
Check::throws(ConfigurationException::class, function () use ($store) { $store->transact('key', function () { return new Change(null, 0, true); }); });
Check::throws(ConfigurationException::class, function () use ($pdo) { MySqlStore::install($pdo); });
Check::same(true, $pdo->inTransaction()); $pdo->rollBack();
Check::same(['n' => 2], $store->transact('key', function ($value) { return new Change($value, 0, $value); }));
$pdo->exec("UPDATE sosecurity_state SET payload='broken' WHERE namespace_hash='" . hash('sha256', 'test') . "'");
Check::throws(StorageException::class, function () use ($store) { $store->transact('key', function () { return new Change(null, 0, true); }); });
$pdo->exec("UPDATE sosecurity_state SET payload=REPEAT('a',65537) WHERE namespace_hash='" . hash('sha256', 'test') . "'");
Check::throws(StorageException::class, function () use ($store) { $store->transact('key', function () { throw new RuntimeException('Oversized payload must never reach callback.'); }); });
$pdo->exec("DELETE FROM sosecurity_state WHERE namespace_hash='" . hash('sha256', 'test') . "'");
$store->transact('expired', function () { return new Change(['n' => 1], 100002, null); });
$clock->time++;
Check::same(1, $store->prune(1));
Check::same(0, $store->prune(1));
$store->transact('metadata', function () { return new Change(['n' => 1], 0, null); });
$pdo->exec("UPDATE sosecurity_state SET expires_at=1 WHERE namespace_hash='" . hash('sha256', 'test') . "'");
Check::throws(StorageException::class, function () use ($store) { $store->transact('metadata', function () { return new Change(null, 0, true); }); });
// The caller's lock remains owned by the caller; timed-out store work is fully rolled back.
$locked = new PDO('mysql:unix_socket=' . $socket . ';dbname=sosecurity_test;charset=utf8mb4', 'sosecurity_test', 'integration-only', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$store->transact('locked', function () { return new Change(['n' => 9], 0, true); });
$locked->beginTransaction();
$query = $locked->prepare('SELECT payload FROM sosecurity_state WHERE namespace_hash=? AND state_key=? FOR UPDATE');
$query->execute([hash('sha256', 'test'), hash('sha256', 'locked')]); $query->fetchColumn();
$started = microtime(true);
Check::throws(StorageException::class, function () use ($store) { $store->transact('locked', function () { throw new RuntimeException('Must never reach callback while locked.'); }); });
Check::same(true, microtime(true) - $started < 3);
Check::same(false, $pdo->inTransaction()); Check::same(true, $locked->inTransaction()); $locked->rollBack();
Check::same((string) $timeout, (string) $pdo->query('SELECT @@SESSION.innodb_lock_wait_timeout')->fetchColumn());
Check::same(['n' => 9], $store->transact('locked', function ($value) { return new Change($value, 0, $value); }));
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_SILENT);
Check::throws(StorageException::class, function () use ($store) { $store->transact('metadata', function () { return new Change(null, 0, null); }); });
Check::same(PDO::ERRMODE_SILENT, $pdo->getAttribute(PDO::ATTR_ERRMODE));
$pdo->setAttribute(PDO::ATTR_ERRMODE, $mode);
$factory = SoSecurity\Security::fromArray(['site' => 'mysql-factory', 'storage' => ['driver' => 'mysql', 'connection' => 'db']], ['db' => $pdo], $clock);
Check::same(true, $factory->rateLimiter()->consume('login', 'a')->allowed);
$report = $factory->diagnose(null, true);
Check::same('pass', array_values(array_filter($report, function ($check) { return $check['check'] === 'storage.shared'; }))[0]['status']);
Check::same(false, $pdo->inTransaction());
$token = $factory->resetTokens()->issue('account:version');
Check::same(true, $factory->resetTokens()->consume('account:version', $token));
Check::same(false, $factory->resetTokens()->consume('account:version', $token));
$store->transact('tombstone', function () { return new Change(null, 0, true); });
$pdo->exec("DELETE FROM sosecurity_state WHERE namespace_hash='" . hash('sha256', 'test') . "' AND state_key!='" . hash('sha256', 'tombstone') . "'");
$clock->time += 61; Check::same(1, $store->prune());
// A real disconnected connection before COMMIT cannot return an accepted security result.
$victim = new class('mysql:unix_socket=' . $socket . ';dbname=sosecurity_test;charset=utf8mb4', 'sosecurity_test', 'integration-only', [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]) extends PDO {
    public $killer;
    public $target;
    public function commit(): bool { $this->killer->exec('KILL CONNECTION ' . $this->target); return parent::commit(); }
};
$victim->killer = $pdo; $victim->target = (int) $victim->query('SELECT CONNECTION_ID()')->fetchColumn();
$failed = new MySqlStore($victim, 'failed-commit', $clock);
Check::throws(StorageException::class, function () use ($failed) { $failed->transact('lost', function () { return new Change(['n' => 1], 0, true); }); });
Check::same(0, (int) $pdo->query("SELECT COUNT(*) FROM sosecurity_state WHERE namespace_hash='" . hash('sha256', 'failed-commit') . "'")->fetchColumn());
Check::throws(StorageException::class, function () use ($failed) { $failed->transact('lost', function () { throw new RuntimeException('Failed connection must never run the callback.'); }); });
$pdo->exec('CREATE TABLE mysql_host_probe (id INT PRIMARY KEY, value INT) ENGINE=InnoDB');
$pdo->exec('INSERT INTO mysql_host_probe VALUES (1,0)');
$pdo->beginTransaction(); $pdo->exec('UPDATE mysql_host_probe SET value=9 WHERE id=1');
Check::throws(ConfigurationException::class, function () use ($store) { $store->prune(); });
Check::same(true, $pdo->inTransaction()); Check::same(9, (int) $pdo->query('SELECT value FROM mysql_host_probe')->fetchColumn());
$pdo->rollBack(); Check::same(0, (int) $pdo->query('SELECT value FROM mysql_host_probe')->fetchColumn());
$pdo->exec('DROP TABLE mysql_host_probe');
$pdo->exec('DROP TABLE sosecurity_state');
$pdo->exec(str_replace('ENGINE=InnoDB', 'ENGINE=MyISAM', MySqlStore::schema()));
Check::throws(ConfigurationException::class, function () use ($pdo) { new MySqlStore($pdo, 'test'); });
$pdo->exec('DROP TABLE sosecurity_state'); MySqlStore::install($pdo);
echo 'PHP ' . PHP_VERSION . ': ' . Check::$assertions . " MySQL driver assertions passed\n";
